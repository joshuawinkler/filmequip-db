#!/usr/bin/env python3
"""
Imports the category tree and per-category field schemas from a Supabase-style
CSV export (categories table + category_field_schemas table) and writes:

  data/categories.json                 - full category tree (id, name, parent_id, sort_order)
  data/schemas/fields/<category_id>.json - dynamic field definitions for categories
                                            that have custom fields

Re-run this any time the source database's categories/field schemas change -
it fully regenerates both outputs from the CSVs (does not touch data/<root>/*.yaml
entries).

Usage:
  python3 scripts/import_categories.py \
      --categories-csv path/to/categories_rows.csv \
      --field-schemas-csv path/to/category_field_schemas_rows.csv
"""

import argparse
import csv
import json
import re
import shutil
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "data"
FIELDS_DIR = DATA_DIR / "schemas" / "fields"
ADMIN_DIR = ROOT / "admin"

# Fork/redeploy elsewhere: change these two and re-run the import script.
GITHUB_REPO = "joshuawinkler/filmequip-db"
OAUTH_PROXY_BASE_URL = "https://decap-proxy.joshuawinkler.workers.dev"

